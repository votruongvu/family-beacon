/**
 * Generated views.
 *
 * A view is a projection of canonical data and never an authority. Each one
 * records the exact canonical files it was built from, with their hashes, so
 * staleness is a question answered at read time — a change to a bound source
 * makes the view stale, unrelated changes elsewhere do not.
 */
import { readDocument, writeDocument } from './frontmatter.mjs';
import { hashText, readUtf8, writeAtomic, now } from './fs-safe.mjs';
import { FARO_VERSION } from './model.mjs';
import { storePath, readCharter, listRequirements, listRoutes, readItem, exists, sectionText } from './store.mjs';
import { routingFreshness } from './routing.mjs';

const GENERATED_NOTICE =
  '<!-- GENERATED BY FARO — DO NOT EDIT. Edit the canonical source and re-run `faro render`. -->';

/** @typedef {{ relative: string, title: string, build: (store: any) => { body: string, bindings: {path:string,hash:string}[] } }} View */

/** @type {Record<string, View>} */
export const VIEWS = {
  compass: {
    relative: 'views/PROJECT_COMPASS.md',
    title: 'Project Compass',
    build: buildCompass,
  },
  requirements: {
    relative: 'views/REQUIREMENTS.md',
    title: 'Requirement Register',
    build: buildRequirements,
  },
  routes: {
    relative: 'views/ROUTES.md',
    title: 'Route Register',
    build: buildRoutes,
  },
};

/**
 * Render one view and write it atomically.
 * @param {import('./store.mjs').Store} store
 * @param {keyof VIEWS} name
 */
export function renderView(store, name) {
  const view = VIEWS[name];
  const { body, bindings } = view.build(store);
  const data = {
    faro_type: 'view',
    generated: true,
    generator: `faro ${FARO_VERSION} (${name})`,
    generated_at: now(),
    source_bindings: bindings,
  };
  const text = writeDocument(data, `${GENERATED_NOTICE}\n\n${body}`);
  writeAtomic(storePath(store, view.relative), text);
  return { relative: view.relative, bindings };
}

/** Render every view. @param {import('./store.mjs').Store} store */
export function renderAllViews(store) {
  return Object.keys(VIEWS).map((name) => renderView(store, name));
}

/**
 * Compare a view against the canonical data it claims to be built from.
 * @param {import('./store.mjs').Store} store
 * @param {keyof VIEWS} name
 * `unverifiable` means the canonical source itself is broken, so the view's
 * freshness cannot be decided. That underlying failure is reported on its own;
 * the view does not report it a second time.
 *
 * @returns {{ name: string, relative: string, state: 'fresh'|'missing'|'stale'|'invalid'|'unverifiable', reason?: string }}
 */
export function viewStatus(store, name) {
  const view = VIEWS[name];
  const result = { name, relative: view.relative };
  let expected;
  try {
    expected = view.build(store).bindings;
  } catch (err) {
    return { ...result, state: 'unverifiable', reason: `cannot rebuild from canonical data — ${err.message}` };
  }
  if (!exists(store, view.relative)) {
    return { ...result, state: 'missing', reason: 'the generated view does not exist' };
  }
  let recorded;
  try {
    const { data } = readDocument(readUtf8(storePath(store, view.relative)), view.relative);
    if (data.faro_type !== 'view' || data.generated !== true || !Array.isArray(data.source_bindings)) {
      return { ...result, state: 'invalid', reason: 'the view is missing its generated-view front matter' };
    }
    recorded = data.source_bindings;
  } catch (err) {
    return { ...result, state: 'invalid', reason: err.message };
  }
  const recordedMap = new Map(recorded.map((entry) => [entry.path, entry.hash]));
  const expectedMap = new Map(expected.map((entry) => [entry.path, entry.hash]));
  for (const [path, hash] of expectedMap) {
    if (!recordedMap.has(path)) {
      return { ...result, state: 'stale', reason: `${path} is not covered by the view` };
    }
    if (recordedMap.get(path) !== hash) {
      return { ...result, state: 'stale', reason: `${path} changed since the view was generated` };
    }
  }
  for (const path of recordedMap.keys()) {
    if (!expectedMap.has(path)) {
      return { ...result, state: 'stale', reason: `${path} no longer exists` };
    }
  }
  return { ...result, state: 'fresh' };
}

/** @param {import('./store.mjs').Store} store */
export function allViewStatuses(store) {
  return Object.keys(VIEWS).map((name) => viewStatus(store, name));
}


function buildCompass(store) {
  const charter = readCharter(store);
  const c = charter.data;
  const lines = [];
  lines.push('# Project Compass');
  lines.push('');
  lines.push(`Charter version ${c.charter_version} · status \`${c.status}\` · updated ${c.updated_at}`);
  lines.push('');
  lines.push('## Vision');
  lines.push('');
  lines.push(sectionText(charter.body, 'Vision') || '_Not yet stated._');
  lines.push('');
  lines.push('## Problem');
  lines.push('');
  lines.push(sectionText(charter.body, 'Problem') || '_Not yet stated._');
  lines.push('');
  lines.push(renderTable('Objectives', ['ID', 'Objective', 'Statement'], c.objectives, (o) => [o.id, o.title, o.statement]));
  lines.push(renderTable('Deliveries', ['ID', 'Delivery', 'Description'], c.deliveries, (d) => [d.id, d.title, d.description]));
  lines.push(renderTable('Milestones', ['ID', 'Milestone', 'Exit outcome'], c.milestones, (m) => [m.id, m.title, m.outcome]));

  lines.push('## Scope');
  lines.push('');
  lines.push('**In scope**');
  lines.push('');
  lines.push(...bullets(c.scope.included));
  lines.push('');
  lines.push('**Out of scope**');
  lines.push('');
  lines.push(...bullets(c.scope.excluded));
  lines.push('');
  lines.push(renderTable('Principles', ['ID', 'Kind', 'Principle'], c.principles, (p) => [p.id, p.kind, p.statement]));
  lines.push(renderTable('Success measures', ['ID', 'Measure'], c.success_measures, (m) => [m.id, m.statement]));
  lines.push(
    renderTable('Stakeholders and decision authority', ['ID', 'Name', 'Role', 'Decides'], c.stakeholders, (s) => [
      s.id,
      s.name,
      s.role,
      s.decision_authority.join(', ') || '—',
    ]),
  );
  return { body: lines.join('\n').replace(/\n{3,}/g, '\n\n').trim(), bindings: [binding(store, 'charter/charter.md')] };
}

function buildRequirements(store) {
  const charter = readCharter(store);
  const deliveries = new Map(charter.data.deliveries.map((d) => [d.id, d.title]));
  const bindings = [binding(store, 'charter/charter.md')];
  const rows = [];
  for (const entry of listRequirements(store)) {
    if (entry.latest === 0) continue;
    const relative = `requirements/${entry.id}/v${entry.latest}.md`;
    bindings.push(binding(store, relative));
    const item = readItem(store, relative, 'requirement');
    rows.push([
      `${item.data.id}@${item.data.version}`,
      item.data.title,
      `\`${item.data.status}\``,
      (item.data.contributes_to_deliveries ?? []).map((id) => deliveries.get(id) ?? id).join(', ') || '—',
      (item.data.aligns_to_objectives ?? []).join(', ') || '—',
    ]);
  }
  const lines = ['# Requirement Register', ''];
  lines.push('Latest version of every requirement. Historical versions stay on disk and are never rewritten.');
  lines.push('');
  if (rows.length === 0) {
    lines.push('_No requirements have been admitted yet. Capture one with `/faro-intake`._');
  } else {
    lines.push('| Version | Requirement | Status | Deliveries | Objectives |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const row of rows) lines.push(`| ${row.join(' | ')} |`);
  }
  return { body: lines.join('\n'), bindings };
}

/**
 * One route register, not four status views.
 *
 * Stale and review-required routes are *sections* of the register rather than
 * views of their own: a second generated file answering "which routes need
 * attention?" would be a second place to look and a second thing to keep true.
 */
function buildRoutes(store) {
  const bindings = [];
  const rows = [];
  for (const id of listRoutes(store)) {
    const relative = `routes/${id}.md`;
    bindings.push(binding(store, relative));
    const route = readItem(store, relative, 'route');
    const data = route.data;
    const source = readSignatureSource(store, data.signature);
    const freshness = routingFreshness(store, data);
    rows.push({
      id,
      source,
      signature: data.signature,
      status: data.status,
      confidence: data.routing_confidence,
      isolation: data.execution_boundary?.recommended_isolation ?? '—',
      write: (data.scope?.write_scope ?? []).length,
      approval: data.approval?.required === 'human' ? (data.approval.granted ? 'approved' : 'awaiting') : 'auto',
      fresh: freshness.fresh,
      reason: freshness.changed[0] ?? null,
      open: ['draft', 'review_required', 'approved'].includes(data.status),
    });
  }

  const lines = ['# Route Register', ''];
  lines.push('Every route contract, and the exact source each one compiled. A route is usable only');
  lines.push('while its bindings are fresh; staleness is computed here, never stored.');
  lines.push('');
  if (rows.length === 0) {
    lines.push('_No routes yet. Compile one with `/faro-route <REQ-ID@VERSION | OBL-ID>`._');
    return { body: lines.join('\n'), bindings };
  }

  lines.push('| Route | Source | Signature | Status | Confidence | Isolation | Writes | Approval | Bindings |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const row of rows) {
    lines.push(
      `| ${row.id} | ${row.source} | ${row.signature} | \`${row.status}\` | ${row.confidence} | ${row.isolation} | ${row.write} | ${row.approval} | ${row.fresh ? 'fresh' : 'STALE'} |`,
    );
  }

  const stale = rows.filter((row) => row.open && !row.fresh);
  if (stale.length > 0) {
    lines.push('', '## Stale routes', '');
    lines.push('These cannot be used until they are rebased and reconsidered.', '');
    for (const row of stale) lines.push(`- **${row.id}** — ${row.reason}`);
  }

  const review = rows.filter((row) => row.open && row.approval === 'awaiting');
  if (review.length > 0) {
    lines.push('', '## Routes awaiting human approval', '');
    for (const row of review) lines.push(`- **${row.id}** (${row.source}) — ${row.confidence} confidence, ${row.isolation} isolation`);
  }

  return { body: lines.join('\n'), bindings };
}

/** The requirement version or obligation a signature compiled, for display. */
function readSignatureSource(store, signatureId) {
  try {
    const signature = readItem(store, `signatures/${signatureId}.md`, 'signature');
    const source = signature.data.source;
    return source.version ? `${source.id}@${source.version}` : source.id;
  } catch {
    return '(unresolved)';
  }
}

function renderTable(heading, columns, rows, project) {
  const lines = [`## ${heading}`, ''];
  if (!rows || rows.length === 0) {
    lines.push('_None recorded yet._', '');
    return lines.join('\n');
  }
  lines.push(`| ${columns.join(' | ')} |`);
  lines.push(`| ${columns.map(() => '---').join(' | ')} |`);
  for (const row of rows) lines.push(`| ${project(row).join(' | ')} |`);
  lines.push('');
  return lines.join('\n');
}

function bullets(values) {
  if (!values || values.length === 0) return ['_None recorded yet._'];
  return values.map((value) => `- ${value}`);
}

function binding(store, relative) {
  return { path: relative, hash: hashText(readUtf8(storePath(store, relative))) };
}
